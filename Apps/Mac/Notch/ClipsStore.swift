/// What the app keeps with each clip. The rules about clips (kinds, age, recopies) are in PerchKit's
/// `ClipShelf`; this is the part only the Mac has: the bytes, the file and the picture.
struct ClipPayload {
    enum Content {
        case text(String)
        /// An image from the pasteboard: its bytes as they were copied, and their type.
        case image(Data, UTType)
        case file(URL)
    }

    var content: Content
    /// Came from the screenshot folder, or carries macOS's screenshot mark: the card says "Screenshot"
    /// or "Screen recording" instead of the long file name.
    var isScreenCapture: Bool
    /// Its picture, made once and kept with it.
    let thumbnail: ClipThumbnail
    /// For text, what its card draws, worked out once however long the text is.
    let summary: String

    init(content: Content, isScreenCapture: Bool = false, thumbnail: ClipThumbnail) {
        self.content = content
        self.isScreenCapture = isScreenCapture
        self.thumbnail = thumbnail
        if case let .text(text) = content { summary = ClipRules.preview(of: text) } else { summary = "" }
    }
}

typealias Clip = ClipShelf<ClipPayload>.Item

extension ClipShelf.Item where Payload == ClipPayload {
    var text: String? {
        if case let .text(text) = payload.content { return text }
        return nil
    }

    var fileURL: URL? {
        if case let .file(url) = payload.content { return url }
        return nil
    }

    var link: ClipLink? { kind == .link ? text.flatMap { ClipLink(text: $0) } : nil }

    /// What the card calls it.
    var title: String {
        switch payload.content {
        case .text: return payload.summary
        case .image: return "Image"
        case let .file(url):
            if payload.isScreenCapture { return kind == .image ? "Screenshot" : "Screen recording" }
            return url.lastPathComponent
        }
    }
}

/// A clip's picture: a small thumbnail of an image or of a file's contents, or else the file's icon.
@MainActor
final class ClipThumbnail: ObservableObject {
    @Published private(set) var image: NSImage?
    /// Only the file's icon: no picture of what is inside could be made.
    @Published private(set) var isIcon: Bool

    init(image: NSImage? = nil, isIcon: Bool = false) {
        self.image = image
        self.isIcon = isIcon
    }

    func show(_ image: NSImage?, isIcon: Bool) {
        self.image = image
        self.isIcon = isIcon
    }
}

/// Recent copies, screenshots and dropped files, one click away in the notch.
///
/// Clips live in memory for a day at most and are gone when Perch quits; nothing about them is written
/// to disk. Expiring or removing one only forgets Perch's note of it: a user's file is never deleted,
/// moved or changed. In a snapshot or stress run (`isLive` false) the store never reads the pasteboard
/// or the disk, runs no timer and saves no setting: it shows only what it is handed.
@MainActor
final class ClipsStore: ObservableObject {
    static let enabledKey = "clipsEnabled"

    @Published private(set) var shelf = ClipShelf<ClipPayload>() {
        didSet { keepFilter() }
    }

    /// The pane's filter, kept while the panel closes and opens again.
    @Published var filter = ClipFilter.all

    @Published var isEnabled: Bool {
        didSet {
            guard isEnabled != oldValue else { return }
            if isLive { UserDefaults.standard.set(isEnabled, forKey: Self.enabledKey) }
            restart()
        }
    }

    let isLive: Bool

    private var timer: Timer?
    private var wakeObserver: NSObjectProtocol?
    private var lastChange = 0
    private var watch = ScreenshotWatch(started: Date())
    /// The screenshot folder as last listed, so it is listed again only when it changes.
    private var folderStamp: (path: String, modified: Date)?

    #if DEBUG
    /// A card drawn as if the pointer were on it, for a snapshot.
    var debugHoveredID: UUID?
    #endif

    // Password managers mark secrets with these types. Never keep those.
    private static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]
    /// Image types taken from the pasteboard, best first. PNG is preferred because it is compact.
    private static let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff, .init(UTType.jpeg.identifier), .init(UTType.heic.identifier)]

    init(isLive: Bool = true) {
        self.isLive = isLive
        isEnabled = isLive && UserDefaults.standard.bool(forKey: Self.enabledKey)
        guard isLive else { return }
        // A Mac that slept through the end of a clip's day must not show it on waking.
        wakeObserver = NSWorkspace.shared.notificationCenter.addObserver(forName: NSWorkspace.didWakeNotification, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.prune() }
        }
        restart()
    }

    private func restart() {
        timer?.invalidate()
        timer = nil
        guard isEnabled else {
            if !shelf.items.isEmpty { shelf = .init() }
            return
        }
        guard isLive else { return }
        lastChange = NSPasteboard.general.changeCount
        watch = ScreenshotWatch(started: Date())
        folderStamp = nil
        let timer = Timer(timeInterval: 1, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        timer.tolerance = 0.3
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func tick() {
        let now = Date()
        prune(now: now)
        checkPasteboard(now: now)
        checkScreenshots(now: now)
    }

    /// Forgets what is a day old. Publishes only when something went, so an open pane isn't redrawn every second.
    func prune(now: Date = Date()) {
        var next = shelf
        if next.prune(now: now) { shelf = next }
    }

    /// The pane is showing: forget anything too old, and files that are no longer there.
    func paneAppeared() {
        prune()
        guard isLive else { return }
        var next = shelf
        let gone = next.removeAll { clip in
            guard let url = clip.fileURL else { return false }
            return !FileManager.default.fileExists(atPath: url.path)
        }
        if gone { shelf = next }
    }

    private func keepFilter() {
        let resolved = shelf.resolved(filter, now: Date())
        if resolved != filter { filter = resolved }
    }

    // MARK: Watching

    private func checkPasteboard(now: Date) {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        if board.types?.contains(where: { Self.secretTypes.contains($0.rawValue) }) == true { return }
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], let url = urls.first {
            addFile(url, at: now)
        } else if let string = board.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(key: .text(string), kind: ClipKind.of(text: string), content: .text(string), at: now)
        } else if let type = board.availableType(from: Self.imageTypes), let data = board.data(forType: type), !data.isEmpty {
            // A screenshot copied straight to the clipboard arrives here. The digest spots the same image copied again.
            let digest = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
            add(key: .image(digest), kind: .image, content: .image(data, UTType(type.rawValue) ?? .image), at: now)
        }
    }

    /// Where macOS saves screenshots: the folder chosen in the Screenshot app, else the Desktop.
    private var screenshotFolder: URL {
        let chosen = UserDefaults(suiteName: "com.apple.screencapture")?.string(forKey: "location")
        let path = chosen.map { ($0 as NSString).expandingTildeInPath } ?? (NSHomeDirectory() as NSString).appendingPathComponent("Desktop")
        // A fresh URL each time: a URL keeps the values it has read, so a kept one would never see the folder change.
        return URL(fileURLWithPath: path, isDirectory: true)
    }

    private func checkScreenshots(now: Date) {
        let folder = screenshotFolder
        // A folder that can't be read is passed over quietly, and nothing here asks for access.
        guard let modified = (try? folder.resourceValues(forKeys: [.contentModificationDateKey]))?.contentModificationDate else { return }
        let changed = folderStamp?.path != folder.path || folderStamp?.modified != modified
        guard changed || watch.isWaiting else { return }
        folderStamp = (folder.path, modified)
        let keys: [URLResourceKey] = [.creationDateKey, .fileSizeKey, .isRegularFileKey]
        guard let urls = try? FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: keys, options: [.skipsHiddenFiles]) else { return }
        let earliest = watch.earliest(now: now)
        var files: [ScreenshotWatch.File] = []
        var byName: [String: URL] = [:]
        for url in urls {
            guard let values = try? url.resourceValues(forKeys: Set(keys)), values.isRegularFile == true,
                  let created = values.creationDate, created >= earliest else { continue }
            let name = url.lastPathComponent
            files.append(.init(name: name, created: created, size: values.fileSize ?? 0, isScreenCapture: ScreenshotWatch.flag(attribute: Self.attribute(of: url))))
            byName[name] = url
        }
        for file in watch.take(files, now: now) {
            guard let url = byName[file.name] else { continue }
            addFile(url, at: file.created, isScreenCapture: true)
        }
    }

    /// The screenshot mark macOS writes on a file, as stored. Nil when the file has none.
    private nonisolated static func attribute(of url: URL) -> Data? {
        url.withUnsafeFileSystemRepresentation { path -> Data? in
            guard let path else { return nil }
            let size = getxattr(path, ScreenshotWatch.attribute, nil, 0, 0, 0)
            guard size > 0, size < 4096 else { return nil }
            var data = Data(count: size)
            let read = data.withUnsafeMutableBytes { getxattr(path, ScreenshotWatch.attribute, $0.baseAddress, size, 0, 0) }
            return read > 0 ? data.prefix(read) : nil
        }
    }

    // MARK: Adding

    /// A file copied in the Finder, dropped on the notch, or a new screenshot. Its kind comes from its
    /// name alone, so nothing is read to decide it.
    func addFile(_ url: URL, at date: Date = Date(), isScreenCapture: Bool? = nil) {
        let url = url.standardizedFileURL
        let kind = ClipKind.of(fileType: UTType(filenameExtension: url.pathExtension))
        let marked = isScreenCapture ?? (isLive && ScreenshotWatch.flag(attribute: Self.attribute(of: url)) == true)
        add(key: .file(url.path), kind: kind, content: .file(url), isScreenCapture: marked, at: date)
    }

    /// A file dropped on the notch: Clips turns on if it was off, and keeps the file.
    func addDropped(_ url: URL) {
        isEnabled = true
        addFile(url)
    }

    private func add(key: ClipKey, kind: ClipKind, content: ClipPayload.Content, isScreenCapture: Bool = false, at date: Date) {
        guard isEnabled else { return }
        // A pasteboard image's bytes are held for copying back, so they count toward the shelf's image budget.
        var cost = 0
        if case let .image(data, _) = content { cost = data.count }
        let item = Clip(key: key, kind: kind, date: date, payload: ClipPayload(content: content, isScreenCapture: isScreenCapture, thumbnail: ClipThumbnail()), cost: cost)
        var next = shelf
        let stored = next.add(item)
        shelf = next
        // A recopy keeps the picture it already has.
        if stored.id == item.id, isLive { ClipPictures.make(for: stored) }
    }

    // MARK: Using

    func copy(_ clip: Clip) {
        guard isLive else { return }
        let board = NSPasteboard.general
        board.clearContents()
        switch clip.payload.content {
        case let .text(text):
            board.setString(text, forType: .string)
            if let link = clip.link { board.setString(link.url.absoluteString, forType: .URL) }
        case let .image(data, type):
            board.setData(data, forType: NSPasteboard.PasteboardType(type.identifier))
        case let .file(url):
            board.writeObjects([url as NSURL])
        }
        // Perch's own copy is not a new clip.
        lastChange = board.changeCount
    }

    /// What a drag out of the pane carries: the text, the address, the image, or the file itself.
    func itemProvider(for clip: Clip) -> NSItemProvider {
        switch clip.payload.content {
        case let .text(text):
            if let link = clip.link {
                let provider = NSItemProvider(object: link.url as NSURL)
                provider.registerObject(text.trimmingCharacters(in: .whitespacesAndNewlines) as NSString, visibility: .all)
                return provider
            }
            return NSItemProvider(object: text as NSString)
        case let .image(data, type):
            return NSItemProvider(item: data as NSData, typeIdentifier: type.identifier)
        case let .file(url):
            return NSItemProvider(contentsOf: url) ?? NSItemProvider(object: url as NSURL)
        }
    }

    func open(_ clip: Clip) {
        guard isLive, let link = clip.link else { return }
        NSWorkspace.shared.open(link.url)
    }

    func showInFinder(_ clip: Clip) {
        guard isLive, let url = clip.fileURL else { return }
        NSWorkspace.shared.activateFileViewerSelecting([url])
    }

    func remove(_ clip: Clip) {
        var next = shelf
        if next.remove(id: clip.id) { shelf = next }
    }

    func removeAll() {
        guard !shelf.items.isEmpty else { return }
        shelf = .init()
    }

    #if DEBUG
    /// Shows these clips, for a picture only. Nothing is read or saved.
    func debugShow(_ items: [Clip], enabled: Bool = true, filter: ClipFilter = .all, hovered: UUID? = nil) {
        isEnabled = enabled
        shelf = ClipShelf(items: enabled ? items : [])
        self.filter = filter
        debugHoveredID = hovered
    }
    #endif
}

/// Makes clip pictures, each once, off the main thread, at the size its card draws them at 2x. Nothing
/// decodes a full-size image on the main thread, and a file is never read whole: ImageIO and Quick Look
/// read only what a thumbnail needs.
enum ClipPictures {
    @MainActor
    static func make(for clip: Clip) {
        let thumbnail = clip.payload.thumbnail
        let fill = pixels(ClipLayout.imageSize)
        switch clip.payload.content {
        case .text:
            return
        case let .image(data, _):
            Task.detached(priority: .utility) {
                let picture = downsample(CGImageSourceCreateWithData(data as CFData, nil), filling: fill)
                await MainActor.run { thumbnail.show(picture.map(image), isIcon: false) }
            }
        case let .file(url):
            guard clip.kind == .image else {
                quickLook(url, size: ClipLayout.fileWell, into: thumbnail)
                return
            }
            Task.detached(priority: .utility) {
                let source = CGImageSourceCreateWithURL(url as CFURL, [kCGImageSourceShouldCache: false] as CFDictionary)
                let picture = downsample(source, filling: fill)
                await MainActor.run {
                    // An image type ImageIO can't read may still have a Quick Look picture.
                    if let picture { thumbnail.show(image(picture), isIcon: false) } else { quickLook(url, size: ClipLayout.imageSize, into: thumbnail) }
                }
            }
        }
    }

    private static func pixels(_ size: CGSize) -> CGSize { CGSize(width: size.width * 2, height: size.height * 2) }

    private static func image(_ picture: CGImage) -> NSImage {
        NSImage(cgImage: picture, size: NSSize(width: CGFloat(picture.width) / 2, height: CGFloat(picture.height) / 2))
    }

    @MainActor
    private static func quickLook(_ url: URL, size: CGSize, into thumbnail: ClipThumbnail) {
        let request = QLThumbnailGenerator.Request(fileAt: url, size: size, scale: 2, representationTypes: .thumbnail)
        QLThumbnailGenerator.shared.generateBestRepresentation(for: request) { representation, _ in
            let picture = representation?.cgImage
            DispatchQueue.main.async {
                MainActor.assumeIsolated {
                    if let picture {
                        thumbnail.show(image(picture), isIcon: false)
                    } else {
                        thumbnail.show(NSWorkspace.shared.icon(forFile: url.path), isIcon: true)
                    }
                }
            }
        }
    }

    /// A thumbnail just big enough to fill `target` pixels (aspect fill), never larger than the image.
    nonisolated static func downsample(_ source: CGImageSource?, filling target: CGSize) -> CGImage? {
        guard let source, CGImageSourceGetCount(source) > 0 else { return nil }
        var longest = max(target.width, target.height)
        if let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
           var width = (properties[kCGImagePropertyPixelWidth] as? NSNumber).map({ CGFloat($0.doubleValue) }),
           var height = (properties[kCGImagePropertyPixelHeight] as? NSNumber).map({ CGFloat($0.doubleValue) }),
           width > 0, height > 0 {
            // Turned on its side by its orientation: the thumbnail comes out turned, so its sides swap.
            if let orientation = (properties[kCGImagePropertyOrientation] as? NSNumber)?.intValue, (5...8).contains(orientation) { swap(&width, &height) }
            let scale = min(max(target.width / width, target.height / height), 1)
            // A very long image (a scrolling capture) is capped, so its thumbnail stays small.
            longest = min((max(width, height) * scale).rounded(.up), 2400)
        }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceShouldCacheImmediately: true,
            kCGImageSourceThumbnailMaxPixelSize: max(longest, 1),
        ]
        return CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary)
    }
}
